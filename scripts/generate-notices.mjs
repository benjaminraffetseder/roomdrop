import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const read = (file) =>
  fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim()
const go = (...args) =>
  execFileSync("go", args, { cwd: root, encoding: "utf8" })
const modules = JSON.parse(go("mod", "edit", "-json")).Require
const moduleDirectories = new Map()

function moduleDirectory(module) {
  if (!moduleDirectories.has(module.Path)) {
    const info = JSON.parse(
      go("mod", "download", "-json", `${module.Path}@${module.Version}`),
    )
    if (!info.Dir) throw new Error(`Cannot locate ${module.Path}`)
    moduleDirectories.set(module.Path, info.Dir)
  }
  return moduleDirectories.get(module.Path)
}

function licenseText(directory) {
  const files = fs
    .readdirSync(directory)
    .filter(
      (name) =>
        /^(licen[cs]e|copying|notice)([.-]|$)/i.test(name) &&
        fs.statSync(path.join(directory, name)).isFile(),
    )
    .sort()
  if (!files.length) throw new Error(`No license notice found in ${directory}`)
  return files.map((name) => read(path.join(directory, name))).join("\n\n")
}

const sections = [
  "# Third-party notices\n\nGenerated by `node scripts/generate-notices.mjs` from the installed production dependencies. Keep these notices with redistributed copies of RoomDrop.\n\nRoomDrop uses the Wails React/TypeScript template and components adapted from shadcn/ui. Linux AppImages also contain their bundled system libraries' copyright notices under `usr/share/doc` and license texts under `usr/share/common-licenses`.",
  `## shadcn/ui\n\n${read(path.join(root, "licenses/shadcn-ui.txt"))}`,
]

const lock = JSON.parse(read(path.join(root, "frontend/package-lock.json")))
const packages = Object.entries(lock.packages)
  .filter(([directory, info]) => directory && !info.dev && !info.devOptional)
  .map(([directory]) => directory)
// These packages ship CSS even though their build tools are dev dependencies.
packages.push(
  "node_modules/tailwindcss",
  "node_modules/shadcn",
  "node_modules/tw-animate-css",
)
for (const directory of [...new Set(packages)].sort()) {
  const location = path.join(root, "frontend", directory)
  const info = JSON.parse(read(path.join(location, "package.json")))
  // The runtime npm tarball omits LICENSE; it is covered by the matching Wails source license.
  let source = location
  if (info.name === "@wailsio/runtime") {
    const wails = modules.find(
      (module) => module.Path === "github.com/wailsapp/wails/v3",
    )
    if (!wails || wails.Version !== `v${info.version}`)
      throw new Error("Wails runtime and Go versions must match.")
    source = moduleDirectory(wails)
  }
  sections.push(
    `## ${info.name} ${info.version}\n\nSource: https://www.npmjs.com/package/${info.name}/v/${info.version}\n\n${licenseText(source)}`,
  )
}

sections.push(
  `## Go standard library\n\nSource: https://go.dev/LICENSE\n\n${read(path.join(go("env", "GOROOT").trim(), "LICENSE"))}`,
)
for (const module of modules.sort((a, b) => a.Path.localeCompare(b.Path))) {
  sections.push(
    `## ${module.Path} ${module.Version}\n\nSource: https://pkg.go.dev/${module.Path}@${module.Version}\n\n${licenseText(moduleDirectory(module))}`,
  )
}

const content = sections.join("\n\n---\n\n") + "\n"
const output = path.join(root, "THIRD_PARTY_NOTICES.md")
const current = fs.existsSync(output)
  ? fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n")
  : ""
if (process.argv.includes("--check")) {
  if (current !== content)
    throw new Error(
      "Third-party notices are stale. Run node scripts/generate-notices.mjs.",
    )
} else if (current !== content) {
  fs.writeFileSync(output, content)
}
console.log(
  `Verified ${packages.length} frontend packages and ${modules.length} Go modules.`,
)
